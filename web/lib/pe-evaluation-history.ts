import type { PeScorecardResult } from './pe-evaluation-scorecard';

export interface PeEvaluationRecord {
  id: string;
  createdAt: string;
  ticker: string;
  stockName: string;
  sector: string;
  purchasePrice: number;
  purchaseDate: string;
  cmp: number | null;
  purchasePe: number | null;
  rawScore: number;
  weightedOverall10: number;
  freshVerdict: string;
  legacyVerdict: string;
  report: string;
  scorecard: PeScorecardResult;
}

interface PeEvaluationIndexFile {
  version: 1;
  entries: PeEvaluationRecord[];
}

interface PeEvaluationHistoryRow {
  id: string;
  user_id: string;
  ticker: string;
  stock_name: string;
  sector: string;
  purchase_price: number;
  purchase_date: string;
  cmp: number | null;
  purchase_pe: number | null;
  raw_score: number;
  weighted_overall_10: number;
  fresh_verdict: string;
  legacy_verdict: string;
  report: string;
  scorecard: PeScorecardResult;
  created_at: string;
}

const PE_EVALUATION_HISTORY_TABLE = 'pe_evaluation_history';

function peEvaluationDir(tenantId: string): string {
  return path.join(getUserPaths(tenantId).portfolioDir, '../stock-calculator/pe-evaluation');
}

function indexPath(tenantId: string): string {
  return path.join(peEvaluationDir(tenantId), 'index.json');
}

async function readIndex(tenantId: string): Promise<PeEvaluationIndexFile> {
  try {
    const raw = await fs.readFile(indexPath(tenantId), 'utf8');
    const parsed = JSON.parse(raw) as PeEvaluationIndexFile;
    if (parsed?.version === 1 && Array.isArray(parsed.entries)) return parsed;
  } catch {
    /* new */
  }
  return { version: 1, entries: [] };
}

async function writeIndex(tenantId: string, data: PeEvaluationIndexFile): Promise<void> {
  const dir = peEvaluationDir(tenantId);
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(indexPath(tenantId), JSON.stringify(data, null, 2), 'utf8');
}

function fmtPe(n: number | null): string {
  if (n == null || !Number.isFinite(n)) return '—';
  return `${n.toFixed(1)}×`;
}

function fmtPct(n: number | null): string {
  if (n == null || !Number.isFinite(n)) return '—';
  const sign = n > 0 ? '+' : '';
  return `${sign}${n.toFixed(1)}%`;
}

export function formatPeScorecardReport(scorecard: PeScorecardResult): string {
  const lines: string[] = [
    `# PE Evaluation Scorecard — ${scorecard.stockName} (${scorecard.ticker})`,
    '',
    `**Sector:** ${scorecard.sector}`,
    `**Purchase:** ₹${scorecard.purchasePrice.toLocaleString('en-IN')} on ${scorecard.purchaseDate}`,
    `**CMP today:** ${scorecard.cmp != null ? `₹${scorecard.cmp.toLocaleString('en-IN')}` : '—'} (${scorecard.cmpSource})`,
    `**Years held:** ${scorecard.yearsHeld}`,
    '',
    '## Part A — Was my purchase good?',
    '',
    `- Purchase P/E: **${fmtPe(scorecard.purchasePe)}** — ${scorecard.purchasePeBand}`,
    `- Purchase EPS: ${scorecard.purchaseEps != null ? `₹${scorecard.purchaseEps.toFixed(1)}` : '—'} (${scorecard.purchaseEpsSource})`,
    '',
    '## Part B — After purchase',
    '',
    `- EPS growth: **${fmtPct(scorecard.epsGrowthSincePurchasePct)}** — ${scorecard.epsGrowthBand}`,
    `- P/E compression rule: ${scorecard.peCompressionRule}`,
    '',
    '## Part C — Attractive today?',
    '',
    '| Metric | Value | Score |',
    '|--------|-------|-------|',
    ...scorecard.metrics.map(
      (m) =>
        `| ${m.label} | ${m.value.replace(/\|/g, '/')} | ${m.signal > 0 ? '+1' : m.signal < 0 ? '−1' : '0'} |`
    ),
    '',
    `- Raw score: **${scorecard.rawScore > 0 ? '+' : ''}${scorecard.rawScore}/8**`,
    `- Valuation: ${scorecard.valuationScore10}/10 · Business: ${scorecard.businessScore10}/10 · Risk: ${scorecard.riskScore10}/10`,
    `- Weighted overall: **${scorecard.weightedOverall10}/10**`,
    '',
    `**Fresh surplus:** ${scorecard.freshVerdict}`,
    '',
    `**Existing holder:** ${scorecard.legacyVerdict}`,
    '',
    '---',
    '',
    '_Generated by Stock Calculator — PE Evaluation Framework. Not investment advice._',
  ];
  return lines.join('\n');
}

export function scorecardToRecord(scorecard: PeScorecardResult, id?: string): PeEvaluationRecord {
  const recordId = id ?? randomUUID();
  return {
    id: recordId,
    createdAt: new Date().toISOString(),
    ticker: scorecard.ticker,
    stockName: scorecard.stockName,
    sector: scorecard.sector,
    purchasePrice: scorecard.purchasePrice,
    purchaseDate: scorecard.purchaseDate,
    cmp: scorecard.cmp,
    purchasePe: scorecard.purchasePe,
    rawScore: scorecard.rawScore,
    weightedOverall10: scorecard.weightedOverall10,
    freshVerdict: scorecard.freshVerdict,
    legacyVerdict: scorecard.legacyVerdict,
    report: formatPeScorecardReport(scorecard),
    scorecard,
  };
}

function rowToRecord(row: PeEvaluationHistoryRow): PeEvaluationRecord {
  return {
    id: row.id,
    createdAt: row.created_at,
    ticker: row.ticker,
    stockName: row.stock_name,
    sector: row.sector,
    purchasePrice: Number(row.purchase_price),
    purchaseDate: row.purchase_date,
    cmp: row.cmp != null ? Number(row.cmp) : null,
    purchasePe: row.purchase_pe != null ? Number(row.purchase_pe) : null,
    rawScore: Number(row.raw_score),
    weightedOverall10: Number(row.weighted_overall_10),
    freshVerdict: row.fresh_verdict,
    legacyVerdict: row.legacy_verdict,
    report: row.report,
    scorecard: row.scorecard,
  };
}

async function persistRecordToDisk(tenantId: string, record: PeEvaluationRecord): Promise<void> {
  const index = await readIndex(tenantId);
  const existing = index.entries.findIndex((e) => e.id === record.id);
  if (existing >= 0) {
    index.entries[existing] = record;
  } else {
    index.entries.unshift(record);
  }
  await writeIndex(tenantId, index);
  await fs.writeFile(
    path.join(peEvaluationDir(tenantId), `${record.id}.md`),
    record.report,
    'utf8'
  );
}

async function fetchAllFromSupabase(userId: string): Promise<PeEvaluationRecord[]> {
  if (isSupabaseTableUnavailable(PE_EVALUATION_HISTORY_TABLE)) return [];

  const supabase = await createClientIfConfigured();
  if (!supabase) return [];

  const { data, error } = await supabase
    .from(PE_EVALUATION_HISTORY_TABLE)
    .select('*')
    .eq('user_id', userId)
    .order('created_at', { ascending: false });

  if (error) {
    if (isMissingTableError(error)) {
      markSupabaseTableUnavailable(PE_EVALUATION_HISTORY_TABLE);
      warnMissingTableOnce(PE_EVALUATION_HISTORY_TABLE, '004_pe_evaluation_history.sql');
      return [];
    }
    if (process.env.NODE_ENV === 'development') {
      console.warn('pe_evaluation_history fetch failed:', error.message);
    }
    return [];
  }

  return (data as PeEvaluationHistoryRow[]).map(rowToRecord);
}

async function fetchOneFromSupabase(
  userId: string,
  id: string
): Promise<PeEvaluationRecord | null> {
  if (isSupabaseTableUnavailable(PE_EVALUATION_HISTORY_TABLE)) return null;

  const supabase = await createClientIfConfigured();
  if (!supabase) return null;

  const { data, error } = await supabase
    .from(PE_EVALUATION_HISTORY_TABLE)
    .select('*')
    .eq('user_id', userId)
    .eq('id', id)
    .maybeSingle();

  if (error) {
    if (isMissingTableError(error)) {
      markSupabaseTableUnavailable(PE_EVALUATION_HISTORY_TABLE);
      warnMissingTableOnce(PE_EVALUATION_HISTORY_TABLE, '004_pe_evaluation_history.sql');
      return null;
    }
    return null;
  }

  if (!data) return null;
  return rowToRecord(data as PeEvaluationHistoryRow);
}

export interface SavePeEvaluationInput {
  tenantId: string;
  userId: string;
  authMode: 'supabase' | 'cookie-dev';
  scorecard: PeScorecardResult;
}

/** Persist PE scorecard run — disk + Supabase; per-user, not linked to portfolio. */
export async function savePeEvaluationRecord(
  input: SavePeEvaluationInput
): Promise<PeEvaluationRecord> {
  assertSafeTenantId(input.tenantId);
  const record = scorecardToRecord(input.scorecard);

  await persistRecordToDisk(input.tenantId, record);

  if (input.authMode === 'supabase') {
    const supabase = await createClientIfConfigured();
    if (supabase && !isSupabaseTableUnavailable(PE_EVALUATION_HISTORY_TABLE)) {
      const { error } = await supabase.from(PE_EVALUATION_HISTORY_TABLE).insert({
        id: record.id,
        user_id: input.userId,
        ticker: record.ticker,
        stock_name: record.stockName,
        sector: record.sector,
        purchase_price: record.purchasePrice,
        purchase_date: record.purchaseDate,
        cmp: record.cmp,
        purchase_pe: record.purchasePe,
        raw_score: record.rawScore,
        weighted_overall_10: record.weightedOverall10,
        fresh_verdict: record.freshVerdict,
        legacy_verdict: record.legacyVerdict,
        report: record.report,
        scorecard: record.scorecard,
      });
      if (error) {
        if (isMissingTableError(error)) {
          markSupabaseTableUnavailable(PE_EVALUATION_HISTORY_TABLE);
          warnMissingTableOnce(PE_EVALUATION_HISTORY_TABLE, '004_pe_evaluation_history.sql');
        } else if (process.env.NODE_ENV === 'development') {
          console.warn('pe_evaluation_history insert failed:', error.message);
        }
      }
    }
  }

  return record;
}

export async function listPeEvaluationRecords(
  tenantId: string,
  userId?: string,
  authMode?: 'supabase' | 'cookie-dev'
): Promise<PeEvaluationRecord[]> {
  assertSafeTenantId(tenantId);
  let entries = (await readIndex(tenantId)).entries;

  if (entries.length === 0 && authMode === 'supabase' && userId) {
    const remote = await fetchAllFromSupabase(userId);
    if (remote.length > 0) {
      for (const record of remote) {
        await persistRecordToDisk(tenantId, record);
      }
      entries = remote;
    }
  }

  return entries.sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

export async function getPeEvaluationRecord(
  tenantId: string,
  id: string,
  userId?: string,
  authMode?: 'supabase' | 'cookie-dev'
): Promise<PeEvaluationRecord | null> {
  const index = await readIndex(tenantId);
  const local = index.entries.find((e) => e.id === id);
  if (local) return local;

  if (authMode === 'supabase' && userId) {
    const remote = await fetchOneFromSupabase(userId, id);
    if (remote) {
      await persistRecordToDisk(tenantId, remote);
      return remote;
    }
  }

  return null;
}

export function groupPeEvaluationByDate(
  entries: PeEvaluationRecord[]
): DateYearGroup<PeEvaluationRecord>[] {
  return groupByYearMonthDate(entries, (e) => e.createdAt);
}
